"""Shared SQLAlchemy foundation for all database models.

Provides:
- the declarative Base with explicit constraint naming (so Alembic
  migrations can reliably drop or alter constraints later);
- reusable column mixins (UUID primary key, timestamps);
- the decimal type used for every monetary amount.

Design rules:
- Money is NEVER stored as float: use MONEY (exact NUMERIC).
- All timestamps are timezone-aware and stored in UTC.
- Statuses are stored as text guarded by CHECK constraints (simpler and
  safer to change in migrations than native PostgreSQL enum types).
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, Numeric, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic names for indexes and constraints.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Exact decimal for money: up to 9,999,999,999.99 with two decimals.
MONEY = Numeric(precision=12, scale=2)


class Base(DeclarativeBase):
    """Declarative base class for every SMART Wi-Fi AutoPay table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """UUID primary key generated by PostgreSQL (or Python as fallback)."""

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )


class CreatedAtMixin:
    """Creation timestamp (UTC), set by the database."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )


class TimestampMixin(CreatedAtMixin):
    """Creation and last-update timestamps (UTC)."""

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
  )
